"""PlatformIO extra script: generates the merged test binary sources.

The test_coverage environment links every non-interactive suite (the union of
the test_logic and test_hardware filters) into one firmware, so a single
flash + run covers everything and a single gcov dump collects all counters.

Each suite is wrapped in its own generated translation unit
(test/test_all/suite_<slug>.cpp) that simply #includes the suite, keeping its
preprocessor state identical to a standalone build.

After each wrapper object compiles, an SCons post action rewrites its symbols
with objcopy:
  - app_main is redefined to suite_<slug>_run (the dispatcher's entry).
  - setUp/tearDown are redefined to suite_<slug>_<hook> when the suite
    defines them (the dispatcher forwards global Unity hooks to these).
  - every other strong global symbol (test functions, helpers, file-scope
    globals such as TAG) is localized, so same-named symbols in different
    suites cannot collide in the merged link.
Weak symbols (C++ inline functions like the shared bus helpers) are left
untouched so they keep merging across translation units.

Suite order in the generated table:
  1. test_logic suites (no hardware).
  2. NRF24L01 - brings up the shared SPI bus for the first radio suite.
  3. IMUGY85 - uses the shared I2C bus from test/shared_test_bus.h.
  4. Remaining hardware suites, WheelController last (its tearDown stops the
     motors).
"""

import json
import os
import re
import subprocess

WHEEL_SUITE = "control/test_WheelController"

HOOK_PATTERN = re.compile(r"^void (setUp|tearDown)\s*\(")

# Tools from the xtensa toolchain package, resolved from the platform env.
OBJCOPY = None
NM = None


def suite_slug(suite):
    return suite.replace("/", "_").lower()


def merged_suite_order(logic, hardware):
    """Order suites: logic first, then NRF24L01, IMUGY85, rest, Wheel last."""
    ordered = list(logic)
    for early in ("NRF24L01/test_NRF24L01", "IMUGY85/test_IMUGY85"):
        if early in hardware:
            ordered.append(early)
    ordered.extend(s for s in hardware if s not in ordered)
    if WHEEL_SUITE in ordered:
        ordered.remove(WHEEL_SUITE)
        ordered.append(WHEEL_SUITE)
    return ordered


def env_test_filter(config, env_name):
    for section in config:
        if section[0] != "env:" + env_name:
            continue
        for key, value in section[1]:
            if key == "test_filter":
                return value
    return []


def suite_hooks(suite_file):
    """Return the subset of setUp/tearDown the suite actually defines."""
    hooks = []
    with open(suite_file) as source:
        for line in source:
            hook = HOOK_PATTERN.match(line)
            if hook:
                hooks.append(hook.group(1))
    return hooks


def generate_merged_sources(env, project_dir):
    raw = subprocess.check_output(
        ["pio", "project", "config", "--json-output"], cwd=project_dir
    )
    config = json.loads(raw)
    logic = env_test_filter(config, "test_logic")
    hardware = env_test_filter(config, "test_hardware")
    suites = merged_suite_order(logic, hardware)

    out_dir = os.path.join(project_dir, "test", "test_all")
    os.makedirs(out_dir, exist_ok=True)

    declarations = []
    table_entries = []
    generated_names = []
    wrapper_objects = []
    for suite in suites:
        slug = suite_slug(suite)
        test_name = suite.rsplit("/", 1)[-1]
        suite_file = os.path.join(project_dir, "test", suite, test_name + ".cpp")
        hooks = suite_hooks(suite_file)

        content = '// Generated by scripts/generate_merged_tests.py - do not edit.\n' + \
            f'#include "../{suite}/{test_name}.cpp"\n'
        wrapper_name = f"suite_{slug}.cpp"
        with open(os.path.join(out_dir, wrapper_name), "w") as wrapper:
            wrapper.write(content)
        generated_names.append(wrapper_name)

        wrapper_objects.append(
            (
                env.subst(
                    os.path.join(
                        "$BUILD_DIR", "test", "test_all", wrapper_name[:-4] + ".o"
                    )
                ),
                slug,
                hooks,
            )
        )

        declarations.append(f"void suite_{slug}_run(void);")
        if "setUp" in hooks:
            declarations.append(f"void suite_{slug}_setUp(void);")
        if "tearDown" in hooks:
            declarations.append(f"void suite_{slug}_tearDown(void);")
        table_entries.append(
            '    {"%s", suite_%s_run, %s, %s},'
            % (
                suite,
                slug,
                f"suite_{slug}_setUp" if "setUp" in hooks else "nullptr",
                f"suite_{slug}_tearDown" if "tearDown" in hooks else "nullptr",
            )
        )

    header = os.path.join(out_dir, "merged_suites.h")
    with open(header, "w") as out:
        out.write(
            "// Generated by scripts/generate_merged_tests.py - do not edit.\n"
            "#ifndef _MERGED_SUITES_H_\n"
            "#define _MERGED_SUITES_H_\n\n"
            "struct MergedSuite\n"
            "{\n"
            "    const char * name;\n"
            "    void (*run)(void);\n"
            "    void (*setup)(void);\n"
            "    void (*teardown)(void);\n"
            "};\n\n"
            "extern const MergedSuite MERGED_SUITES[];\n"
            "extern const int MERGED_SUITE_COUNT;\n\n"
            "// The suite entry points and hook functions have C linkage: the\n"
            "// renamed setUp/tearDown definitions inherit it from unity.h's\n"
            "// extern \"C\" block.\n"
            "extern \"C\" {\n"
            + "\n".join(declarations)
            + "\n}\n\n#endif  // _MERGED_SUITES_H_\n"
        )

    table = os.path.join(out_dir, "merged_suites.cpp")
    with open(table, "w") as out:
        out.write(
            "// Generated by scripts/generate_merged_tests.py - do not edit.\n"
            '#include "merged_suites.h"\n\n'
            "const MergedSuite MERGED_SUITES[] = {\n"
            + "\n".join(table_entries)
            + "\n};\n\n"
            "const int MERGED_SUITE_COUNT =\n"
            "  sizeof(MERGED_SUITES) / sizeof(MERGED_SUITES[0]);\n"
        )
    generated_names.extend(["merged_suites.h", "merged_suites.cpp"])

    # Symbol-fixup data for scripts/fixup_merged_objects.py, which objcopy's
    # the compiled wrapper objects between the build and the final link.
    manifest = os.path.join(out_dir, "merged_manifest.json")
    with open(manifest, "w") as out:
        json.dump(
            {
                "suites": [
                    {
                        "slug": slug,
                        "hooks": hooks,
                        "object": os.path.relpath(path, project_dir),
                    }
                    for path, slug, hooks in wrapper_objects
                ]
            },
            out,
            indent=2,
        )
    generated_names.append("merged_manifest.json")

    # Drop wrappers of suites that disappeared from the filters.
    for existing in os.listdir(out_dir):
        if existing.startswith("suite_") and existing not in generated_names:
            os.remove(os.path.join(out_dir, existing))


def _generate_if_coverage(env):
    if env["PIOENV"] == "test_coverage":
        generate_merged_sources(env, env["PROJECT_DIR"])


_Import = globals().get("Import")
if _Import is not None:
    _Import("env")
    env = globals()["env"]
    _generate_if_coverage(env)
